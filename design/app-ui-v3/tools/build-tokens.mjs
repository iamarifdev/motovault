// Reads Sky's canonical tokens.json and emits CSS custom properties plus a small TS module for motion.
// MotoVault only adds a brand-accent overlay on top (see src/styles/base.css). Nothing here is hand-copied.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const tokens = JSON.parse(readFileSync(resolve(root, 'tokens/sky-tokens.json'), 'utf8'))

const kebab = (s) => s.replace(/([A-Z])/g, '-$1').toLowerCase()
const px = (n) => `${n}px`

function color(hex) {
  const h = hex.replace('#', '')
  const a = parseInt(h.slice(0, 2), 16)
  const rgb = h.slice(2)
  if (a === 255) return `#${rgb}`
  const r = parseInt(rgb.slice(0, 2), 16), g = parseInt(rgb.slice(2, 4), 16), b = parseInt(rgb.slice(4, 6), 16)
  return `rgba(${r}, ${g}, ${b}, ${(a / 255).toFixed(2)})`
}

const lines = []
const add = (name, value) => lines.push(`  --${name}: ${value};`)

for (const [k, v] of Object.entries(tokens.palette)) add(`sky-palette-${kebab(k)}`, color(v))
for (const [k, v] of Object.entries(tokens.spacing)) add(`sp-${kebab(k)}`, px(v))
for (const [k, v] of Object.entries(tokens.radii)) add(`r-${kebab(k)}`, px(v))
for (const [k, v] of Object.entries(tokens.dimensions)) add(`dim-${kebab(k)}`, px(v))
for (const [k, t] of Object.entries(tokens.typography)) {
  add(`type-${kebab(k)}-size`, px(t.size))
  add(`type-${kebab(k)}-weight`, t.weight)
  add(`type-${kebab(k)}-tracking`, `${t.letterSpacing ?? 0}px`)
}
for (const [k, m] of Object.entries(tokens.motion)) {
  add(`dur-${kebab(k)}-enter`, `${m.enterMs}ms`)
  add(`dur-${kebab(k)}-exit`, `${m.exitMs}ms`)
  add(`ease-${kebab(k)}`, `cubic-bezier(${m.curve.join(', ')})`)
}

const semantic = (mode) =>
  Object.entries(tokens.semantic[mode]).map(([role, palette]) => `  --sky-${kebab(role)}: var(--sky-palette-${kebab(palette)});`).join('\n')

const css = `/* Generated by tools/build-tokens.mjs from tokens/sky-tokens.json. Do not edit. */
:root {
${lines.join('\n')}
}
:root, [data-theme="light"] {
${semantic('light')}
}
[data-theme="dark"] {
${semantic('dark')}
}
`

const ts = `// Generated by tools/build-tokens.mjs from tokens/sky-tokens.json. Do not edit.
export const skyMotion = ${JSON.stringify(
  Object.fromEntries(Object.entries(tokens.motion).map(([k, m]) => [k, { enter: m.enterMs / 1000, exit: m.exitMs / 1000, curve: m.curve }])),
  null, 2)} as const
export const skyDims = ${JSON.stringify(tokens.dimensions, null, 2)} as const
export const skyRadii = ${JSON.stringify(tokens.radii, null, 2)} as const
`

mkdirSync(resolve(root, 'src/styles'), { recursive: true })
writeFileSync(resolve(root, 'src/styles/tokens.generated.css'), css)
writeFileSync(resolve(root, 'src/tokens.generated.ts'), ts)
console.log('sky tokens written:', lines.length, 'custom properties')
