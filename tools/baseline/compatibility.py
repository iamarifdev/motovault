def png(red,green,blue):
    def chunk(kind,data):
        return struct.pack('!I',len(data))+kind+data+struct.pack('!I',zlib.crc32(kind+data)&0xffffffff)
    return b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',struct.pack('!IIBBBBB',1,1,8,2,0,0,0))+chunk(b'IDAT',zlib.compress(bytes([0,red,green,blue])))+chunk(b'IEND',b'')


def kotlin_source():
    cases={name:json.loads((p00.FIXTURES/'native'/f'{name}.json').read_text()) for name in p00.SCENARIOS}
    cases.update({name:json.loads((OUT/f'{name}.json').read_text()) for name in ['legacy-minimal','current-all-fields']})
    entries=[]
    for name,value in cases.items():
        payload=json.dumps(value,ensure_ascii=False,separators=(',',':'))
        entries.append(f'        "{name}" to """{payload}"""')
    return '// Generated by tools/baseline/compatibility.py. Synthetic records only.\npackage com.motovault.app.ui\n\ninternal object P00FixtureData {\n    val cases = mapOf(\n'+',\n'.join(entries)+'\n    )\n}\n'


def generate():
    OUT.mkdir(parents=True,exist_ok=True)
    paired=json.loads((p00.FIXTURES/'documents.json').read_text())['native']
    legacy={'ride':{key:value for key,value in paired['ride'].items() if key in ['brandId','edition','year','odometer']},
            'rules':[],'logs':[dict(title='Fuel fill-up',detail='2.0 L',date='2026-10-01',odometer=12000.0,cost=240.0)],
            'documents':[],'appearance':'LIGHT'}
    # Older imports missing IDs generate defaults on decode. The raw fixture is preserved as an input;
    # native tests pin round-trip identity after the first successful decode, never across fresh decodes.
    p00.write_json(OUT/'legacy-minimal.json',legacy)
    current=copy.deepcopy(paired)
    assets=[]
    for name,color in [('p00-original.png',(49,90,190)),('p00-accepted.png',(82,123,210)),('p00-preview.png',(210,220,240))]:
        path=OUT/'assets'/name;path.parent.mkdir(exist_ok=True)
        content=png(*color);path.write_bytes(content)
        assets.append(dict(id=name,bytes=len(content),sha256=hashlib.sha256(content).hexdigest(),synthetic=True))
    current['documents'][0]['pages']=[dict(originalId='p00-original.png',previewId='p00-preview.png',
        acceptedId='p00-accepted.png',mimeType='image/png',width=1,height=1,side='Page 1')]
    current['logs'].append(dict(id='p00-service',title='Workshop visit',detail='Synthetic service',date='2026-10-02',
        odometer=12000.0,kind='service',cost=1600.0,workshop='P00 synthetic workshop',
        serviceLines=[dict(customName='Synthetic part',quantity=2.0,unitPricePoisha=75000,
                           scheduleId='p00-chain',resetsScheduleBaseline=True)],
        serviceLabourPoisha=15000,serviceMiscellaneousPoisha=0,serviceDiscountPoisha=5000,
        serviceTotalPoisha=160000,scheduleIds=['p00-chain'],
        receiptBase64=base64.b64encode((OUT/'assets/p00-original.png').read_bytes()).decode()))
