// Regenerate app-owned icon paths from the exact dependency used by app-ui-v3.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const source = path.join(root, 'design/app-ui-v3/node_modules/lucide-react')
const version = JSON.parse(fs.readFileSync(path.join(source, 'package.json'))).version
const icons = {
  fuel: 'fuel', gauge: 'gauge', sparkles: 'sparkles', 'folder-open': 'folder-open',
  'scan-line': 'scan-line', bike: 'bike', tool: 'wrench', home: 'house',
  history: 'history', user: 'user', plus: 'plus', x: 'x',
  'file-text': 'file-text', droplet: 'droplet', droplets: 'droplets',
  'chevron-right': 'chevron-right', 'chevron-down': 'chevron-down',
  'arrow-left': 'arrow-left', 'map-pin': 'map-pin', camera: 'camera',
  'edit-2': 'pencil', copy: 'copy', 'trash-2': 'trash-2', minus: 'minus',
  bell: 'bell', sun: 'sun', search: 'search', check: 'check',
  'share-2': 'share-2', grid: 'layout-grid', 'undo-2': 'undo-2',
  timer: 'timer', 'triangle-alert': 'triangle-alert', 'circle-check': 'circle-check',
  'help-circle': 'circle-help', lock: 'lock-keyhole', shield: 'shield-check',
}
function shapePath(tag, a) {
  if (tag === 'path') return a.d
  if (tag === 'line') return `M${a.x1} ${a.y1}L${a.x2} ${a.y2}`
  if (tag === 'polyline' || tag === 'polygon') return `M${a.points}${tag === 'polygon' ? 'Z' : ''}`
  if (tag === 'circle') return `M${+a.cx - +a.r} ${a.cy}a${a.r} ${a.r} 0 1 0 ${2 * +a.r} 0a${a.r} ${a.r} 0 1 0 ${-2 * +a.r} 0`
  if (tag === 'rect') {
    const x = +a.x, y = +a.y, w = +a.width, h = +a.height
    const rx = Math.min(+(a.rx ?? a.ry ?? 0), w / 2)
    const ry = Math.min(+(a.ry ?? a.rx ?? 0), h / 2)
    if (!rx || !ry) return `M${x} ${y}h${w}v${h}h${-w}Z`
    return `M${x + rx} ${y}h${w - 2 * rx}a${rx} ${ry} 0 0 1 ${rx} ${ry}v${h - 2 * ry}a${rx} ${ry} 0 0 1 ${-rx} ${ry}h${2 * rx - w}a${rx} ${ry} 0 0 1 ${-rx} ${-ry}v${2 * ry - h}a${rx} ${ry} 0 0 1 ${rx} ${-ry}Z`
  }
  throw new Error(`Unsupported Lucide shape: ${tag}`)
}
const entries = Object.entries(icons).map(([key, name]) => {
  const js = fs.readFileSync(path.join(source, `dist/esm/icons/${name}.js`), 'utf8')
  const array = js.slice(js.indexOf('[', js.indexOf('createLucideIcon(')), js.lastIndexOf(']);') + 1)
  const nodes = Function(`"use strict"; return (${array})`)()
  return `    "fi_${key}.svg" to listOf(\n${nodes.map(([tag, attrs]) => `        ${JSON.stringify(shapePath(tag, attrs))}`).join(',\n')}\n    )`
})
const output = `// Generated by tools/build-v3-icons.mjs from lucide-react ${version} (ISC).\n// Artwork source: design/app-ui-v3; license: composeResources/files/licenses/lucide.txt.\npackage com.motovault.app.ui\n\ninternal val v3IconPaths: Map<String, List<String>> = mapOf(\n${entries.join(',\n')}\n)\n`
const target = path.join(root, 'composeApp/src/commonMain/kotlin/com/motovault/app/ui/V3IconPaths.kt')
const license = path.join(root, 'composeApp/src/commonMain/composeResources/files/licenses/lucide.txt')
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8') !== output || fs.readFileSync(license, 'utf8') !== fs.readFileSync(path.join(source, 'LICENSE'), 'utf8')) throw new Error('V3 icon paths or license are stale')
} else {
  fs.writeFileSync(target, output)
  fs.mkdirSync(path.dirname(license), { recursive: true })
  fs.copyFileSync(path.join(source, 'LICENSE'), license)
}
console.log(`${entries.length} v3 Lucide icons ${process.argv.includes('--check') ? 'verified' : 'generated'} (${version})`)
